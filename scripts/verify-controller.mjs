import assert from 'node:assert/strict';
import { readController, defaultControllerSettings, stick } from '../lib/controller.ts';
import { InputSystem, toTraversalInput } from '../lib/input-system.ts';
const settings = defaultControllerSettings();
const pad = (buttons = [], axes = [0,0,0,0]) => ({ buttons: Array.from({length:18}, (_, i) => ({pressed:buttons.includes(i), value:buttons.includes(i)?1:0})), axes });
const input = new InputSystem();
const sample = (p, policy = {}, combat = false, grounded = false) => { const c = readController(p,settings,combat,grounded); input.setController(c.held,c.moveX,c.moveY); return input.sample(policy); };
assert.equal(sample(pad([7])).swing.pressed,true);
assert.equal(sample(pad([7])).swing.pressed,false);
assert.equal(sample(null).swing.released,true);
assert.equal(sample(pad([6,7])).zip.pressed,true);
assert.equal(sample(pad([6,7])).swing.held,false);
assert.equal(sample(pad([7,0]),{},false,true).chargeJump.held,true);
assert.equal(sample(pad([7,0]),{},false,true).jump.held,false);
assert.equal(sample(pad([7])).chargeJump.released,true);
assert.equal(sample(pad([2]),{},true).attack.pressed,true);
assert.equal(sample(pad([2]),{},true).trick.held,false);
assert.equal(sample(pad([4,2]),{},true).heavy.pressed,true);
assert.equal(sample(pad([4,2]),{},true).attack.held,false);
assert.equal(sample(pad([7]),{enabled:false}).swing.held,false);
assert.equal(sample(pad([7])).swing.pressed,true);
input.loseFocus();
assert.equal(sample(pad([7])).swing.held,false);
input.gainFocus();
assert.equal(sample(pad([7])).swing.pressed,true);
assert.equal(sample(pad([],[.08,.05,0,0])).moveX,0);
const move = toTraversalInput(sample(pad([],[.4,-.4,0,0])),{x:0,y:0,z:-1}).move;
assert.ok(move.x>0 && move.z<0 && Math.hypot(move.x,move.z)<1);
assert.ok(Math.abs(Math.hypot(...Object.values(stick(1,1)))-1)<1e-8);
settings.bindings.swing=[5];
assert.equal(sample(pad([5])).swing.pressed,true);
assert.equal(sample(pad([7])).swing.held,false);
assert.equal(readController(null,settings).lookX,0);
console.log('PASS controller edges, disconnect, chords, combat context, countdown, focus, analog movement, radial deadzone, remapping');
