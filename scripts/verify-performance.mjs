import assert from 'node:assert/strict';
import * as THREE from 'three';
import { TraversalTelemetry, PERFORMANCE_CHANNELS } from '../lib/telemetry.ts';
import { RenderQualityManager, qualitySettings } from '../lib/render-quality.ts';
import { TraversalSpeedBlur } from '../lib/traversal-camera.ts';

const telemetry = new TraversalTelemetry(100);
for (let i = 1; i <= 200; i++) for (const channel of PERFORMANCE_CHANNELS) telemetry.record(channel, i);
telemetry.record('frame', NaN); telemetry.record('frame', -1);
telemetry.setRenderCounters({ drawCalls: 132, triangles: 54000, textures: 21, geometries: 34 });
const snapshot = telemetry.snapshot();
assert.equal(snapshot.timings.frame.count, 100);
assert.equal(snapshot.timings.frame.p50Ms, 150);
assert.equal(snapshot.timings.frame.p95Ms, 195);
assert.equal(snapshot.timings.frame.p99Ms, 199);
assert.equal(snapshot.renderer.drawCalls, 132);
assert.equal(new TraversalTelemetry().snapshot().timings.frame.p95Ms, null);
console.log('PASS telemetry ring bounds memory, rejects invalid samples, reports real percentiles and render counts');

const quality = new RenderQualityManager(), changed = [];
for (let i = 0; i < 2200; i++) if (quality.update(1 / 60, 32)) changed.push(quality.settings);
assert.deepEqual(changed.map(item => item.level), [1, 2, 3, 4, 5, 6]);
for (const settings of changed.slice(0, 5)) assert.equal(settings.resolutionScale, 1);
assert.equal(changed[0].weatherDensity, 1);
assert.equal(changed[1].particleDensity, 1);
assert.equal(changed[3].secondaryAnimationHz, 60);
assert.equal(changed[4].secondaryAnimationHz, 20);
assert.equal(changed[5].resolutionScale, .85);
for (let i = 0; i < 4200; i++) quality.update(1 / 60, 16);
assert.deepEqual(quality.settings, qualitySettings(0));
const stable = new RenderQualityManager();
for (let i = 0; i < 2000; i++) stable.update(1 / 60, i % 2 ? 25 : 16);
assert.equal(stable.settings.level, 0);
for (let i = 0; i < 300; i++) stable.update(2, 2000, false);
assert.equal(stable.settings.level, 0);
console.log('PASS quality degrades in required order, recovers, rejects tab pause samples and resists threshold oscillation');

const blur = new TraversalSpeedBlur();
blur.resize(1000, 500); assert.deepEqual(blur.targetSize, { width: 850, height: 425 });
blur.setResolutionScale(.65); assert.deepEqual(blur.targetSize, { width: 650, height: 325 });
const scene = new THREE.Scene(), camera = new THREE.PerspectiveCamera();
let target = null, calls = [], targetChanges = 0;
const renderer = { getRenderTarget: () => target, setRenderTarget(value) { target = value; targetChanges++; }, render(s, c) { calls.push({ scene: s, camera: c, target }); } };
blur.update(1 / 60, 0, false); blur.render(renderer, scene, camera);
assert.equal(calls.length, 1); assert.equal(calls[0].scene, scene); assert.equal(targetChanges, 0);
calls = []; blur.update(1 / 60, 90, true); blur.render(renderer, scene, camera);
assert.equal(calls.length, 2); assert.ok(calls[0].target); assert.equal(calls[1].target, null); assert.equal(target, null);
calls = []; blur.update(1 / 60, 90, true, true); blur.render(renderer, scene, camera);
assert.equal(calls.length, 1); assert.equal(calls[0].scene, scene);
blur.dispose();
console.log('PASS blur bypasses offscreen work at zero/reduced motion, scales only active target, and restores renderer state');
console.log('Scope: deterministic policy and render-call tests. Pixel color and GPU/frame performance require browser verification.');
